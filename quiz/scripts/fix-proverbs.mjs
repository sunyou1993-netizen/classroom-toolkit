/* ── 실행 ─────────────────────────────────────────────── */
function 바꾸기(찾을키, 표, 만들기) {
  let 총 = 0;
  const 못찾음 = [];
  for (const [옛, 새] of Object.entries(표)) {
    let 찾음 = false;
    for (const f of 파일들) {
      let s = fs.readFileSync(f, 'utf8');
      const 자리 = s.indexOf(`proverb:"${옛}"`);
      if (자리 < 0) continue;
      const [시작, 길이, 값] = 만들기(s, 자리, 새);
      if (시작 < 0) continue;
      s = s.slice(0, 시작) + 값 + s.slice(시작 + 길이);
      fs.writeFileSync(f, s);
      찾음 = true; 총++;
    }
    if (!찾음) 못찾음.push(옛);
  }
  return { 총, 못찾음 };
}

