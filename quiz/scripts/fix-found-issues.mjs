/* 이름으로 항목을 찾아 그 항목의 meaning 만 통째로 바꿉니다. */
function 뜻갈아끼우기(파일들, 열쇠, 표) {
  let 총 = 0;
  const 못찾음 = [];
  for (const [이름, 뜻] of Object.entries(표)) {
    let 찾음 = false;
    for (const f of 파일들) {
      let s = fs.readFileSync(f, 'utf8');
      const 자리 = s.indexOf(열쇠 + ':"' + 이름 + '"');
      if (자리 < 0) continue;
      const 뒤 = s.slice(자리, 자리 + 600);
      const m = 뒤.match(/meaning:"(?:[^"\\]|\\.)*"/);
      if (!m) continue;
      const 시작 = 자리 + 뒤.indexOf(m[0]);
      s = s.slice(0, 시작) + 'meaning:' + JSON.stringify(뜻) + s.slice(시작 + m[0].length);
      fs.writeFileSync(f, s);
      찾음 = true; 총++;
    }
    if (!찾음) 못찾음.push(이름);
  }
  return { 총, 못찾음 };
}

{
  const a = 뜻갈아끼우기(번들('fourchar'), 'idiom', 새뜻);
  const b = 뜻갈아끼우기(번들('proverb'), 'proverb', 새속담뜻);
  console.log(`■ 뜻풀이 ${a.총 + b.총}건을 고쳤습니다`);
  const 못 = [...a.못찾음, ...b.못찾음];
  if (못.length) console.log('  ✗ 못 찾은 항목:', 못.join(', '));
}

