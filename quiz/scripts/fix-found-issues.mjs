/* ── 1. 호환 한자 바로잡기 ───────────────────────────────── */
{
  let 고친글자 = 0, 고친파일 = 0;
  for (const f of 번들('fourchar')) {
    const s = fs.readFileSync(f, 'utf8');
    // hanja:"..." 안의 글자만 정규화합니다. 다른 곳을 건드리지 않습니다.
    let 이번 = 0;
    const 새 = s.replace(/hanja:"([^"]*)"/g, (전체, 한자) => {
      const 바꾼 = [...한자].map((c) => {
        const cp = c.codePointAt(0);
        if (cp >= 0xF900 && cp <= 0xFAFF) { 이번++; return c.normalize('NFKC'); }
        return c;
      }).join('');
      return 'hanja:"' + 바꾼 + '"';
    });
    if (이번) { fs.writeFileSync(f, 새); 고친글자 += 이번; 고친파일++; }
  }
  console.log(`■ 호환 한자 ${고친글자}자를 정상 한자로 바로잡았습니다 (파일 ${고친파일}개)`);
}

