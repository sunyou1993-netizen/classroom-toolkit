/* 제가 낸 실수를 되돌립니다.
 *
 * 무슨 일이 있었나:
 *   O/X 균형을 맞추려고 다섯 문항의 묻는 방향을 뒤집었는데,
 *   그 직전에 문항 두 개를 지우면서 번호를 다시 매긴 것을 잊고
 *   **옛 번호**로 뒤집었습니다. 그래서 엉뚱한 다섯 문항이 덮어써졌고,
 *   덮어쓴 문장과 그 자리에 남아 있던 출처가 서로 맞지 않게 되었습니다.
 *
 *   예: 69번이 "피해 학생은 아무런 보호도 받을 수 없어요"로 바뀌었는데
 *       출처는 그 자리에 있던 '초1·2 관계회복 프로그램' 보도자료였습니다.
 *
 * 어떻게 고치나:
 *   1) 덮어써진 다섯 문항을 원래대로 되돌립니다.
 *   2) 다시 뒤집되, 이번에는 **번호가 아니라 문장으로** 찾습니다.
 *      번호는 문항을 지우면 밀리지만 문장은 밀리지 않습니다.
 *   3) 뒤집은 문항이 자기 출처와 여전히 맞는지 확인하고 화면에 보여 줍니다.
 *
 * 사용법: node scripts/fix-flip-mistake.mjs
 */
import fs from 'fs';
import path from 'path';

const 파일 = path.join(process.cwd(), 'scripts', 'questions', 'violence.json');
const 목록 = JSON.parse(fs.readFileSync(파일, 'utf8'));

/* 1) 덮어써진 다섯 문항 되돌리기 — 지금 들어 있는 문장으로 찾아 원래 문장으로 */
const 되돌릴것 = [
  { 지금: '사이버폭력을 당하면 그 화면을 바로 지우는 것이 좋아요.',
    q: '사이버폭력에는 온라인에서의 언어폭력과 명예훼손이 들어가요.', ans: 'O',
    exp: '맞아요! 온라인에서 하는 욕설과 명예훼손도 사이버폭력이에요.' },
  { 지금: '인터넷에 한번 퍼진 글이나 영상은 지워 달라고 할 수 없어요.',
    q: '온라인에서는 얼굴을 보지 않으니 무슨 말을 해도 학교폭력이 아니에요.', ans: 'X',
    exp: '틀려요! 얼굴을 보지 않아도 마음에 상처를 주면 학교폭력이에요.' },
  { 지금: '아직 학교폭력이 일어나지 않았으면 미리 알릴 수 없어요.',
    q: '학교 안에 있는 위(Wee) 클래스에서 상담을 받을 수 있어요.', ans: 'O',
    exp: '맞아요! 학교 안 위(Wee) 클래스에서 상담 선생님을 만날 수 있어요.' },
  { 지금: '학교폭력을 다루는 사람은 관련된 학생 이야기를 남에게 말해도 돼요.',
    q: '피해를 입은 학생은 학교에서 상담이나 치료 같은 보호를 받을 수 있어요.', ans: 'O',
    exp: '맞아요! 심리상담, 치료, 요양 같은 보호 조치를 받을 수 있어요.' },
  { 지금: '피해를 입은 학생은 학교에서 아무런 보호도 받을 수 없어요.',
    q: '초등학교 1~2학년 사이의 일은 심의 전에 관계회복을 먼저 해 보기도 해요.', ans: 'O',
    exp: '맞아요! 초등 1~2학년은 심의 전에 관계회복을 먼저 해 볼 수 있어요.' },
];

let 되돌림 = 0;
for (const r of 되돌릴것) {
  const x = 목록.find((y) => y.q === r.지금);
  if (!x) { console.error('✗ 되돌릴 문항을 못 찾았습니다:', r.지금); process.exit(1); }
  x.q = r.q; x.ans = r.ans; x.exp = r.exp;
  되돌림++;
}
console.log(`■ 덮어써진 ${되돌림}문항을 원래대로 되돌렸습니다`);

/* 2) 다시 뒤집기 — 번호가 아니라 문장으로 찾습니다.
 *    뒤집어도 그 문항의 출처가 여전히 뒷받침하는 것만 골랐습니다. */
const 뒤집을것 = [
  { 찾을문장: '사이버폭력을 당했다면 그 화면을 저장해 두는 것이 도움이 돼요.',
    q: '사이버폭력을 당하면 그 화면을 바로 지우는 것이 좋아요.', ans: 'X',
    exp: '틀려요! 화면을 저장해 두어야 나중에 도움을 받을 수 있어요.' },
  { 찾을문장: '인터넷에 퍼진 피해 영상이나 글은 지워 달라고 도움을 요청할 수 있어요.',
    q: '인터넷에 퍼진 피해 영상이나 글은 지워 달라고 할 수 없어요.', ans: 'X',
    exp: '틀려요! 지워 달라고 요청하고 도움을 받을 수 있어요.' },
  { 찾을문장: '학교폭력을 아직 당하지 않았어도, 그런 일이 준비되는 걸 알면 알릴 수 있어요.',
    q: '아직 학교폭력이 일어나지 않았으면 미리 알릴 수 없어요.', ans: 'X',
    exp: '틀려요! 그런 일이 준비되는 것을 알게 되어도 바로 알릴 수 있어요.' },
  { 찾을문장: '학교폭력을 다루는 사람은 관련된 학생의 개인정보를 함부로 말하면 안 돼요.',
    q: '학교폭력을 다루는 사람은 관련된 학생 이야기를 남에게 말해도 돼요.', ans: 'X',
    exp: '틀려요! 알게 된 개인정보나 사실을 함부로 말하면 안 돼요.' },
  { 찾을문장: '학교는 피해 학생과 가해 학생의 관계 회복을 돕는 프로그램을 운영할 수 있어요.',
    q: '학교는 피해 학생과 가해 학생의 관계 회복을 도울 수 없어요.', ans: 'X',
    exp: '틀려요! 학교장은 필요하면 관계 회복 프로그램을 운영할 수 있어요.' },
];

console.log('\n■ 다시 뒤집습니다 (문장으로 찾아서)');
for (const f of 뒤집을것) {
  const x = 목록.find((y) => y.q === f.찾을문장);
  if (!x) { console.error('✗ 뒤집을 문항을 못 찾았습니다:', f.찾을문장); process.exit(1); }
  x.q = f.q; x.ans = f.ans; x.exp = f.exp;
  console.log(`  ${String(x.id).padStart(2)}번  O → X   ${f.q}`);
  console.log(`        근거 그대로: ${x.근거문서.slice(0, 70)}`);
}

/* 3) 번호 다시 매기고 저장 */
목록.forEach((x, i) => { x.id = i + 1; });
fs.writeFileSync(파일, JSON.stringify(목록, null, 1) + '\n');

const O = 목록.filter((x) => x.ans === 'O').length;
console.log(`\n학교폭력 ${목록.length}문항 · O ${O} : X ${목록.length - O}`);

/* 4) 같은 말을 하는 문항이 생기지 않았는지 확인 */
const 본 = new Map();
let 중복 = 0;
목록.forEach((x) => { if (본.has(x.q)) { console.error('✗ 중복:', 본.get(x.q), x.id, x.q); 중복++; } 본.set(x.q, x.id); });
console.log(중복 ? `✗ 중복 ${중복}건` : '중복 없음 ✓');
